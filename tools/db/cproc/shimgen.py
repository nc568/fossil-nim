#!/usr/bin/env python3
"""Generate the cproc shim modules from the *installed* Nim stdlib.

The engine itself is plain C11, but Nim's standard library contains three
constructs cproc cannot compile:

  1. `pure/hashes.nim` emits a `__uint128_t` multiplication when `gcc` is
     defined — and `-d:gcc` is set by `--cc:gcc` no matter which compiler is
     used afterwards. cproc has no 128-bit integers.
  2. `pure/parseutils.nim` switches on character *ranges*
     (`of '0'..'9':`), a GNU extension Nim emits because it assumes `gcc`.
     cproc is strict C11.
  3. Nim's generated C includes `<math.h>` for `fabs` alone, and musl's
     `<math.h>` declares `long double` prototypes (`sqrtl`, `powl`) that cproc
     rejects while parsing the header.

None of these are semantics we want, so the shim removes the *spelling* and
keeps the *behaviour*:

  * hashes: the `__uint128_t` branch is disabled, which selects Nim's own
    128-bit fallback (`hiXorLoFallback64`) — the reference implementation of
    the same function, only slower.
  * parseutils: every `of 'a'..'z':` becomes `of 'a', 'b', ... 'z':`, which is
    the expansion Nim itself performs for compilers without the GNU extension.
  * math.h: a minimal header with the double-precision subset.

Everything here is *derived* at gate time from the stdlib that is actually
installed, never copied into the repo: if Nim's stdlib changes, the shim
changes with it and the gate stays honest. `--check` verifies the derivation
still produces what we expect.
"""
import argparse
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent

PARSEUTILS_RANGE = re.compile(r"of '(.)'\.\.'(.)':")
HASHES_EMIT = "elif defined(gcc) or defined(llvm_gcc) or defined(clang):"

MATH_H = """\
/* Minimal <math.h> for the cproc gate (generated by shimgen.py).
 *
 * musl declares long double prototypes (sqrtl, powl, ...) that cproc cannot
 * parse. The engine needs only the double subset, and only `fabs` today.
 * Anything not declared here fails the gate loudly on purpose. */
#ifndef _FoccilCprocMathH
#define _FoccilCprocMathH
double fabs(double);
double floor(double);
double ceil(double);
double trunc(double);
double round(double);
double sqrt(double);
double pow(double, double);
double fmod(double, double);
#endif
"""


def pinned(key: str) -> str:
    """Read a pin from versions.env (the gate's single source of truth)."""
    env = HERE / "versions.env"
    for line in env.read_text().splitlines():
        line = line.strip()
        if line.startswith(key + "="):
            return line.split("=", 1)[1].strip()
    sys.exit(f"shimgen: {key} missing from {env}")


def check_nim_version() -> None:
    """The shim rewrites stdlib files by shape, so it is only valid for the Nim
    it was written against. A silent mismatch would mean silently not patching
    (the regex finds nothing), and then the gate fails with a confusing error
    three steps later — so fail here, with the reason."""
    exe = subprocess.run(["sh", "-c", "command -v nim"], capture_output=True, text=True).stdout.strip()
    if not exe:
        sys.exit("shimgen: nim not on PATH")
    out = subprocess.run([exe, "--version"], capture_output=True, text=True).stdout
    m = re.search(r"Version ([0-9.]+)", out)
    actual = m.group(1) if m else "unknown"
    expect = pinned("NIM_VERSION")
    if actual != expect:
        sys.exit(f"shimgen: Nim {actual} is installed, but the gate pins {expect} "
                 f"(tools/db/cproc/versions.env). The stdlib shim is derived by "
                 f"shape and is only validated against the pinned version — run "
                 f"tools/db/bootstrap.sh, or update the pin deliberately.")


def nim_lib() -> pathlib.Path:
    """Locate the stdlib of the Nim that will do the codegen."""
    import shutil, subprocess
    exe = shutil.which("nim")
    if exe is None:
        sys.exit("shimgen: nim not on PATH")
    out = subprocess.run([exe, "dump", "--dump.format:json"],
                         capture_output=True, text=True)
    if out.returncode == 0:
        import json
        try:
            lib = json.loads(out.stdout).get("libPath")
            if lib:
                return pathlib.Path(lib)
        except json.JSONDecodeError:
            pass
    # fallback: <prefix>/bin/nim -> <prefix>/lib
    guess = pathlib.Path(exe).resolve().parent.parent / "lib"
    if not (guess / "system.nim").exists():
        sys.exit("shimgen: cannot find the Nim stdlib; set NIM_LIB")
    return guess


def expand_ranges(text: str) -> tuple[str, int]:
    def sub(m: re.Match) -> str:
        lo, hi = ord(m.group(1)), ord(m.group(2))
        return "of " + ", ".join("'%s'" % chr(c) for c in range(lo, hi + 1)) + ":"
    return PARSEUTILS_RANGE.subn(sub, text)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir", type=pathlib.Path)
    ap.add_argument("--lib", type=pathlib.Path, default=None)
    ap.add_argument("--skip-version-check", action="store_true",
                    help="for developing the shim itself; never in the gate")
    ap.add_argument("--check", action="store_true",
                    help="only verify that the derivation still applies")
    ap.add_argument("--install", action="store_true",
                    help="patch the installed stdlib in place (needed: stdlib "
                         "modules imported as `std/x` bypass patchFile)")
    args = ap.parse_args()
    if not args.skip_version_check:
        check_nim_version()
    lib = args.lib or nim_lib()

    # Always derive from the pristine copy: after `--install` the stdlib file
    # is already patched, and re-deriving from it would find nothing (or worse,
    # patch twice). The `.foccil-orig` backup is the source of truth.
    def pristine(name: str) -> str:
        backup = lib / "pure" / f"{name}.nim.foccil-orig"
        return (backup if backup.exists() else lib / "pure" / f"{name}.nim").read_text()

    parseutils = pristine("parseutils")
    patched, n = expand_ranges(parseutils)
    if n == 0:
        sys.exit("shimgen: no character ranges found in parseutils.nim — "
                 "the stdlib changed; re-check whether cproc needs this shim")

    hashes = pristine("hashes")
    if HASHES_EMIT not in hashes:
        sys.exit("shimgen: hashes.nim no longer has the gcc __uint128_t branch")
    patched_hashes = hashes.replace(
        HASHES_EMIT,
        "# cproc has no __uint128_t: take the portable fallback (shimgen.py)\n"
        "    elif false:")

    if args.check:
        print(f"shimgen: ok — {n} character ranges expanded, hashes branch found")
        return 0

    header = "# Generated by tools/db/cproc/shimgen.py — do not edit, do not commit\n"
    if args.install:
        for name in ("parseutils", "hashes"):
            target = lib / "pure" / f"{name}.nim"
            backup = lib / "pure" / f"{name}.nim.foccil-orig"
            body = header + (patched if name == "parseutils" else patched_hashes)
            if not backup.exists():
                backup.write_text(target.read_text())
            if target.read_text() != body:
                target.write_text(body)
        print(f"shimgen: patched {lib}/pure/{{parseutils,hashes}}.nim "
              f"(backups: *.foccil-orig)")
        return 0

    args.outdir.mkdir(parents=True, exist_ok=True)
    (args.outdir / "parseutils.nim").write_text(header + patched)
    (args.outdir / "hashes.nim").write_text(header + patched_hashes)
    (args.outdir / "math.h").write_text(MATH_H)
    print(f"shimgen: {args.outdir} — {n} ranges expanded, hashes fallback selected")
    return 0


if __name__ == "__main__":
    sys.exit(main())
